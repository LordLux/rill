/// `RILL_CAPTIONS_PROBE=1` — task 17's measurements, from the real app.
///
/// Same family as `RILL_CONTROLS_PROBE`, and for the same reason: three of the
/// things this task has to answer are only observable against real libmpv in a
/// real window, and none of them is reachable from a widget test.
///
/// 1. **Does attaching a caption track rebuild the video output?** This is a
///    stop condition. A quality switch costs 0.55–12 s precisely because it
///    reopens the media (F19), and if `sub-add` did the same, captions would
///    have to become a per-open choice rather than a free toggle. The instrument
///    is F19's own: `VideoController.id` changes when the output is rebuilt.
/// 2. **Do captions survive a quality switch?** The switch *does* reopen, so
///    mpv drops external subtitle tracks with it. `MediaKitEngine.open` is
///    supposed to put the track back.
/// 3. **Can the bundled libass actually render what `ass.ts` emits?** mpv's own
///    track list is the answer — a document it rejected is not in it.
///
/// Unset, this costs one environment lookup at startup.
library;

