void runCaptionsProbe(ProviderContainer container) {
  final mode = Platform.environment['RILL_CAPTIONS_PROBE'];
  if (mode != '1' && mode != 'synthetic') return;
  WidgetsBinding.instance.addPostFrameCallback(
    (_) => unawaited(mode == 'synthetic' ? _syntheticProbe(container) : _probe(container)),
  );
}

void _say(String line) => stderr.writeln('captions-probe: $line');

Future<void> _wait([int millis = 2000]) => Future<void>.delayed(Duration(milliseconds: millis));

/// mpv's own track list, as `type[*]:codec` per entry.
///
/// A diagnostics-only property read, off the UI isolate's critical path and
/// never polled — hard invariant 9's carve-out, the same one
/// `audio_delay_probe.dart` uses. It is the only way to see whether libass
/// *accepted* a document: a rejected one leaves the picture looking identical.
Future<String> _mpvTracks(PlaybackEngine engine) async {
  if (engine is! MediaKitEngine) return 'n/a';
  try {
    final count = await engine.diagnostics.getProperty('track-list/count');
    final n = int.tryParse(count) ?? 0;
    final out = <String>[];
    for (var i = 0; i < n; i++) {
      final type = await engine.diagnostics.getProperty('track-list/$i/type');
      final selected = await engine.diagnostics.getProperty('track-list/$i/selected');
      final codec = await engine.diagnostics.getProperty('track-list/$i/codec');
      out.add('$type${selected == 'yes' ? '*' : ''}:$codec');
    }
    return out.isEmpty ? '(none)' : out.join(' ');
  } on Object catch (e) {
    return 'unreadable ($e)';
  }
}

